"""Функции для вычисления площади и периметра квадрата."""


def area(a):
    """Возвращает площадь квадрата со стороной a."""
    if a < 0:
        raise ValueError("Сторона не может быть отрицательной")
    return a ** 2


def perimeter(a):
    """Возвращает периметр квадрата со стороной a."""
    if a < 0:
        raise ValueError("Сторона не может быть отрицательной")
    return 4 * a
